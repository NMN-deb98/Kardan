/** Pure helpers (unit-tested): fuzzy search over the user's own list and link validation. */
object MovieSearch {
    fun haystack(w: WatchItem): String =
        listOf(w.title, w.originalTitle, w.altNames, w.genre, w.year, w.type).joinToString(" ")

    fun filter(all: List<WatchItem>, query: String, type: String?, status: String?): List<WatchItem> =
        all.filter { (type == null || it.type == type) && (status == null || it.status == status) && Fuzzy.matches(haystack(it), query) }

    /** Only https links the user typed are opened; nothing is ever generated by the app. */
    fun validLink(link: String): Boolean {
        val l = link.trim()
        return l.startsWith("https://") && l.length > 12 && !l.contains(" ")
    }
}

private fun typeIcon(t: String) = if (t == "فیلم") Icons.Filled.Movie else Icons.Filled.Tv

@Composable
fun MoviesScreen(state: AppState, title: String, onBack: () -> Unit) {
    val c = K.c
    val host = LocalHost.current
    var q by remember { mutableStateOf("") }
    var typeFilter by remember { mutableStateOf<String?>(null) }
    var statusFilter by remember { mutableStateOf<String?>(null) }
    var editing by remember { mutableStateOf<WatchItem?>(null) }
    var creating by remember { mutableStateOf(false) }
    var deleting by remember { mutableStateOf<WatchItem?>(null) }
    val list = MovieSearch.filter(state.watch.toList(), q, typeFilter, statusFilter)

    Page(title, "بخش مستقل فیلم و سریال؛ جدا از جست‌وجوی عمومی اینترنت", onBack) {
        KCard {
            Row(verticalAlignment = Alignment.Top, horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                Icon(Icons.Filled.Info, null, tint = c.accent)
                Column(verticalArrangement = Arrangement.spacedBy(4.dp), modifier = Modifier.weight(1f)) {
                    Text("وضعیت این بخش", style = MaterialTheme.typography.titleMedium, color = c.text)
                    Text("فهرست شخصی تو با مشخصات کامل (نام فارسی و اصلی، سال، ژانر، خلاصه، مدت، امتیاز) کار می‌کند. کاتالوگ آنلاین با پوستر و امتیاز عمومی هنوز وصل نیست؛ برای وصل‌کردنش باید مجوز استفاده، هزینه، پوشش محتوای فارسی، محدودیت منطقه‌ای و شرایط نمایش پوستر یک منبع رسمی بررسی شود. تا آن موقع داده‌ای حدس زده نمی‌شود و لینک تماشا فقط همان است که خودت وارد کنی.", style = MaterialTheme.typography.bodySmall, color = c.muted)
                }
            }
        }
        KField(q, { q = it }, "جست‌وجو در فهرست: نام فارسی، انگلیسی، ژانر یا سال", trailing = { Icon(Icons.Filled.Search, null, tint = c.muted) })
        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Chip("همه", typeFilter == null) { typeFilter = null }
            Categories.watchTypes.forEach { t -> Chip(t, typeFilter == t) { typeFilter = if (typeFilter == t) null else t } }
        }
        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Chip("هر وضعیت", statusFilter == null) { statusFilter = null }
            Categories.watchStatus.forEach { k -> Chip(k, statusFilter == k) { statusFilter = if (statusFilter == k) null else k } }
        }
        KButton("افزودن فیلم یا سریال", { creating = true }, Modifier.fillMaxWidth(), icon = Icons.Filled.Add)

        if (state.watch.isEmpty()) EmptyState(Icons.Filled.Movie, "فهرست خالی است", "هر فیلم، سریال، انیمیشن یا مستندی که می‌خواهی ببینی را با مشخصاتش اینجا بنویس و بعد از دیدن امتیاز بده.")
        else if (list.isEmpty()) EmptyState(Icons.Filled.Search, "نتیجه‌ای در فهرست تو پیدا نشد", "املا را عوض کن یا فیلتر را بردار. این بخش فقط در فهرست خودت می‌گردد و از اینترنت نتیجه نمی‌آورد.")

        list.forEach { w ->
            val idx = state.watch.indexOfFirst { it.id == w.id }
            KCard {
                Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                    // poster placeholder: generated art only, never a copyrighted poster
                    Box(
                        Modifier.width(72.dp).height(104.dp).clip(RoundedCornerShape(14.dp)).background(Brush.linearGradient(listOf(c.heroA, c.heroB))),
                        contentAlignment = Alignment.Center
                    ) { Icon(typeIcon(w.type), null, tint = Color.White.copy(alpha = 0.9f), modifier = Modifier.size(34.dp)) }
                    Column(Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                        Text(w.title, style = MaterialTheme.typography.titleMedium, color = c.text, maxLines = 2, overflow = TextOverflow.Ellipsis)
                        if (w.originalTitle.isNotBlank()) LtrText(w.originalTitle, color = c.muted, style = MaterialTheme.typography.bodySmall)
                        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                            Tag(w.type)
                            if (w.year.isNotBlank()) Tag(Persian.digits(w.year), c.muted)
                            if (w.genre.isNotBlank()) Tag(w.genre, c.muted)
                            if (w.duration.isNotBlank()) Tag(Persian.digits(w.duration), c.muted)
                        }
                        Tag(w.status, if (w.status == "دیده‌شده") c.ok else if (w.status == "در حال تماشا") c.accent else c.warn)
                    }
                }
                if (w.summary.isNotBlank()) Text(w.summary, style = MaterialTheme.typography.bodySmall, color = c.muted, maxLines = 3, overflow = TextOverflow.Ellipsis)
                Row(verticalAlignment = Alignment.CenterVertically) {
                    for (i in 1..5) IconButton(onClick = { state.watch[idx] = w.copy(rating = if (w.rating == i) 0 else i); state.saveWatch() }) {
                        Icon(if (i <= w.rating) Icons.Filled.Star else Icons.Filled.StarBorder, "امتیاز من $i", tint = if (i <= w.rating) c.warn else c.muted)
                    }
                    Text(if (w.rating > 0) "امتیاز تو" else "امتیاز تو (هنوز نداده‌ای)", style = MaterialTheme.typography.bodySmall, color = c.muted)
                }
                Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    val next = Categories.watchStatus[(Categories.watchStatus.indexOf(w.status) + 1) % Categories.watchStatus.size]
                    KOutlineButton("← $next", { state.watch[idx] = w.copy(status = next); state.saveWatch() })
                    if (MovieSearch.validLink(w.link)) KOutlineButton("لینک تماشا", { host.openUrl(w.link.trim()) }, icon = Icons.Filled.OpenInNew)
                    KOutlineButton("ویرایش", { editing = w }, icon = Icons.Filled.Edit)
                    IconButton(onClick = { deleting = w }) { Icon(Icons.Filled.Delete, "حذف", tint = c.muted) }
                }
            }
        }
    }

    if (creating) WatchEditor(null, onDismiss = { creating = false }) { item ->
        state.watch.add(0, item.copy(id = state.newId())); state.saveWatch(); creating = false
    }
    editing?.let { e ->
        WatchEditor(e, onDismiss = { editing = null }) { item ->
            val i = state.watch.indexOfFirst { it.id == e.id }
            if (i >= 0) { state.watch[i] = item.copy(id = e.id, rating = e.rating); state.saveWatch() }
            editing = null
        }
    }
    deleting?.let { d ->
        AlertDialog(
            onDismissRequest = { deleting = null },
            title = { Text("حذف از فهرست؟") }, text = { Text("«${d.title}» از فهرست تو حذف می‌شود.") },
            confirmButton = { TextButton(onClick = { state.watch.removeAll { it.id == d.id }; state.saveWatch(); deleting = null }) { Text("حذف", color = c.danger) } },
            dismissButton = { TextButton(onClick = { deleting = null }) { Text("انصراف") } }
        )
    }
}

@Composable
private fun WatchEditor(initial: WatchItem?, onDismiss: () -> Unit, onSave: (WatchItem) -> Unit) {
    val c = K.c
    val host = LocalHost.current
    var title by remember { mutableStateOf(initial?.title ?: "") }
    var original by remember { mutableStateOf(initial?.originalTitle ?: "") }
    var alt by remember { mutableStateOf(initial?.altNames ?: "") }
    var year by remember { mutableStateOf(initial?.year ?: "") }
    var genre by remember { mutableStateOf(initial?.genre ?: "") }
    var duration by remember { mutableStateOf(initial?.duration ?: "") }
    var summary by remember { mutableStateOf(initial?.summary ?: "") }
    var link by remember { mutableStateOf(initial?.link ?: "") }
    var type by remember { mutableStateOf(initial?.type ?: Categories.watchTypes[0]) }
    var status by remember { mutableStateOf(initial?.status ?: Categories.watchStatus[0]) }
    var error by remember { mutableStateOf<String?>(null) }
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text(if (initial == null) "افزودن به فهرست" else "ویرایش") },
        text = {
            Column(Modifier.verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) { Categories.watchTypes.forEach { t -> Chip(t, type == t) { type = t } } }
                KField(title, { title = it; error = null }, "عنوان فارسی *")
                KField(original, { original = it }, "عنوان اصلی (انگلیسی یا زبان اصلی)")
                KField(alt, { alt = it }, "نام یا املای دیگر (با ویرگول جدا کن)")
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    KField(year, { year = it.filter { ch -> ch.isDigit() || ch in '۰'..'۹' }.take(4) }, "سال", Modifier.weight(1f), keyboard = KeyboardType.Number)
                    KField(genre, { genre = it }, "ژانر", Modifier.weight(1.4f))
                }
                KField(duration, { duration = it }, "مدت یا تعداد قسمت‌ها")
                KField(summary, { summary = it }, "خلاصه", singleLine = false, minLines = 3)
                KField(link, { link = it; error = null }, "لینک تماشای قانونی (اختیاری)", keyboard = KeyboardType.Uri)
                Text("لینک را خودت از صفحهٔ همان عنوان در یک سرویس قانونی بردار؛ کاردان لینک نمی‌سازد و دوبله، زیرنویس یا امکان تماشا در ایران را تأیید نمی‌کند.", style = MaterialTheme.typography.bodySmall, color = c.muted)
                Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) { Categories.watchStatus.forEach { k -> Chip(k, status == k) { status = k } } }
                error?.let { Text(it, color = c.danger, style = MaterialTheme.typography.bodySmall) }
            }
        },
        confirmButton = {
            TextButton(onClick = {
                when {
                    title.isBlank() -> error = "عنوان فارسی را بنویس."
                    link.isNotBlank() && !MovieSearch.validLink(link) -> error = "لینک باید با https:// شروع شود و فاصله نداشته باشد."
                    else -> onSave((initial ?: WatchItem(0, "")).copy(
                        title = title.trim(), originalTitle = original.trim(), altNames = alt.trim(), year = Persian.latinDigits(year), genre = genre.trim(),
                        duration = duration.trim(), summary = summary.trim(), link = link.trim(), type = type, status = status
                    ))
                }
            }) { Text("ذخیره") }
        },
        dismissButton = { TextButton(onClick = onDismiss) { Text("انصراف") } }
    )
}
